export function isLocale(value: string): value is Locale {
  return value === "ko" || value === "en";
}

export function getDict(lang: string) {
  return lang === "en" ? en : ko;
}

export function errorText(lang: Locale, code: string | undefined) {
  if (!code) return "";
  const dict = getDict(lang).errors;
  if (code in dict) return dict[code as keyof typeof dict];
  return dict.invalid;
}
